package infrastructure

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"io"
	"net/http"
	"net/url"
	"regexp"
	"strings"
	"time"

	"github.com/google/uuid"
	"github.com/minio/minio-go/v7"
	"github.com/minio/minio-go/v7/pkg/credentials"
)

const MaxImageBytes = 2 * 1024 * 1024

var (
	ErrInvalidImage  = errors.New("only JPEG, PNG and WebP images are allowed")
	ErrImageTooLarge = errors.New("image exceeds 2 MiB")
	ErrImageNotFound = errors.New("image not found")
	filenamePattern  = regexp.MustCompile(`^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(jpg|png|webp)$`)
)

type MinIOStore struct {
	client    *minio.Client
	bucket    string
	publicURL string
}

// NewMinIO connects to the existing MinIO server and creates the image bucket
// if it has not yet been initialized. No PostgreSQL schema changes are performed.
func NewMinIO(ctx context.Context, endpoint, accessKey, secretKey, bucket, publicAPIURL string, useSSL bool) (*MinIOStore, error) {
	if endpoint == "" || accessKey == "" || secretKey == "" || bucket == "" || publicAPIURL == "" {
		return nil, errors.New("MinIO endpoint, credentials, bucket and public API URL are required")
	}
	if strings.Contains(endpoint, "://") || strings.Contains(endpoint, "/") {
		return nil, errors.New("MINIO_ENDPOINT must be host:port, without a URL scheme or path")
	}
	base, err := url.Parse(publicAPIURL)
	if err != nil || base.Host == "" || (base.Scheme != "http" && base.Scheme != "https") || (base.Path != "" && base.Path != "/") || base.RawQuery != "" || base.Fragment != "" {
		return nil, errors.New("PUBLIC_API_URL must be an absolute http(s) origin without a path")
	}
	client, err := minio.New(endpoint, &minio.Options{
		Creds:  credentials.NewStaticV4(accessKey, secretKey, ""),
		Secure: useSSL,
	})
	if err != nil {
		return nil, err
	}
	checkCtx, cancel := context.WithTimeout(ctx, 8*time.Second)
	defer cancel()
	exists, err := client.BucketExists(checkCtx, bucket)
	if err != nil {
		return nil, fmt.Errorf("minio bucket check: %w", err)
	}
	if !exists {
		if err := client.MakeBucket(checkCtx, bucket, minio.MakeBucketOptions{}); err != nil {
			return nil, fmt.Errorf("minio create bucket %q: %w", bucket, err)
		}
	}
	return &MinIOStore{client: client, bucket: bucket, publicURL: strings.TrimSuffix(publicAPIURL, "/")}, nil
}

// ImageFormat checks the actual bytes rather than trusting the supplied file extension/MIME.
func ImageFormat(data []byte) (contentType, extension string, err error) {
	if len(data) > MaxImageBytes {
		return "", "", ErrImageTooLarge
	}
	if len(data) == 0 {
		return "", "", ErrInvalidImage
	}
	// net/http.DetectContentType does not recognize WebP. Validate its RIFF/WEBP
	// container signature and the first image chunk type explicitly.
	if len(data) >= 16 && bytes.Equal(data[:4], []byte("RIFF")) && bytes.Equal(data[8:12], []byte("WEBP")) {
		switch string(data[12:16]) {
		case "VP8 ", "VP8L", "VP8X":
			return "image/webp", "webp", nil
		}
	}
	switch http.DetectContentType(data) {
	case "image/jpeg":
		return "image/jpeg", "jpg", nil
	case "image/png":
		return "image/png", "png", nil
	case "image/webp":
		return "image/webp", "webp", nil
	default:
		return "", "", ErrInvalidImage
	}
}

func imageKey(scope, ownerID, filename string) (string, error) {
	if scope != "users" && scope != "products" {
		return "", ErrImageNotFound
	}
	if _, err := uuid.Parse(ownerID); err != nil {
		return "", ErrImageNotFound
	}
	if !filenamePattern.MatchString(filename) {
		return "", ErrImageNotFound
	}
	return scope + "/" + ownerID + "/" + filename, nil
}

func (s *MinIOStore) Upload(ctx context.Context, scope, ownerID string, data []byte) (string, error) {
	mime, ext, err := ImageFormat(data)
	if err != nil {
		return "", err
	}
	filename := uuid.NewString() + "." + ext
	key, err := imageKey(scope, ownerID, filename)
	if err != nil {
		return "", err
	}
	opCtx, cancel := context.WithTimeout(ctx, 25*time.Second)
	defer cancel()
	_, err = s.client.PutObject(opCtx, s.bucket, key, bytes.NewReader(data), int64(len(data)), minio.PutObjectOptions{
		ContentType: mime, ContentDisposition: "inline", CacheControl: "public, max-age=31536000, immutable",
	})
	if err != nil {
		return "", fmt.Errorf("minio upload: %w", err)
	}
	return s.publicURL + "/media/" + key, nil
}

// managedKey only trusts URLs generated by this server and never deletes old
// Cloudinary/external images during the transition to MinIO.
func (s *MinIOStore) managedKey(imageURL string) (string, bool) {
	parsed, err := url.Parse(imageURL)
	if err != nil {
		return "", false
	}
	origin, err := url.Parse(s.publicURL)
	if err != nil || parsed.Scheme != origin.Scheme || parsed.Host != origin.Host || parsed.RawQuery != "" || parsed.Fragment != "" {
		return "", false
	}
	if !strings.HasPrefix(parsed.Path, "/media/") {
		return "", false
	}
	segments := strings.Split(strings.TrimPrefix(parsed.Path, "/media/"), "/")
	if len(segments) != 3 {
		return "", false
	}
	key, err := imageKey(segments[0], segments[1], segments[2])
	return key, err == nil
}

func (s *MinIOStore) Delete(ctx context.Context, imageURL string) error {
	key, managed := s.managedKey(imageURL)
	if !managed {
		return nil
	}
	opCtx, cancel := context.WithTimeout(ctx, 10*time.Second)
	defer cancel()
	return s.client.RemoveObject(opCtx, s.bucket, key, minio.RemoveObjectOptions{})
}

func (s *MinIOStore) Get(ctx context.Context, scope, ownerID, filename string) (StoredImage, error) {
	key, err := imageKey(scope, ownerID, filename)
	if err != nil {
		return StoredImage{}, err
	}
	opCtx, cancel := context.WithTimeout(ctx, 15*time.Second)
	defer cancel()
	obj, err := s.client.GetObject(opCtx, s.bucket, key, minio.GetObjectOptions{})
	if err != nil {
		return StoredImage{}, mapMinIOError(err)
	}
	defer obj.Close()
	info, err := obj.Stat()
	if err != nil {
		return StoredImage{}, mapMinIOError(err)
	}
	if info.Size < 0 || info.Size > MaxImageBytes {
		return StoredImage{}, ErrImageTooLarge
	}
	contentType := strings.TrimSpace(strings.SplitN(info.ContentType, ";", 2)[0])
	switch contentType {
	case "image/jpeg", "image/png", "image/webp":
	default:
		return StoredImage{}, ErrInvalidImage
	}
	data, err := io.ReadAll(io.LimitReader(obj, MaxImageBytes+1))
	if err != nil {
		return StoredImage{}, mapMinIOError(err)
	}
	if len(data) > MaxImageBytes {
		return StoredImage{}, ErrImageTooLarge
	}
	return StoredImage{Body: data, ContentType: contentType}, nil
}

func mapMinIOError(err error) error {
	switch minio.ToErrorResponse(err).Code {
	case "NoSuchKey", "NoSuchObject", "NoSuchBucket", "NotFound":
		return ErrImageNotFound
	default:
		return err
	}
}
